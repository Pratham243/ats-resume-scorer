from typing import Any, Dict, List
import streamlit as st


def display_star_rewrites(analysis: Dict[str, Any]) -> None:
    """
    Renders high-converting STAR (Situation, Task, Action, Result) bullet point rewrites
    generated by the Drafter Agent.
    """
    rewrites: List[Dict[str, Any]] = analysis.get("star_rewrites") or []
    if not rewrites:
        return

    st.markdown("### ⭐ AI Drafter Agent: STAR-Method Bullet Rewrites")
    st.caption(
        "The Drafter Agent evaluated your resume experience and transformed weak or metric-sparse "
        "statements into high-impact accomplishments using the Google XYZ / STAR formula."
    )

    for idx, rewrite in enumerate(rewrites, 1):
        original = rewrite.get("original", "")
        improved = rewrite.get("improved_bullet", "")
        situation = rewrite.get("star_situation", "")
        task = rewrite.get("star_task", "")
        action = rewrite.get("star_action", "")
        result = rewrite.get("star_result", "")
        explanation = rewrite.get("impact_explanation", "")

        with st.container():
            st.markdown(
                f"""
                <div style="background-color: #f8fafc; border: 1px solid #e2e8f0; 
                            border-left: 5px solid #4f46e5; border-radius: 8px; 
                            padding: 1.25rem; margin-bottom: 1.25rem;">
                    <div style="font-size: 0.8rem; font-weight: 700; color: #ef4444; 
                                text-transform: uppercase; letter-spacing: 0.05em; margin-bottom: 0.25rem;">
                        ⚠️ Original Draft
                    </div>
                    <div style="font-style: italic; color: #475569; margin-bottom: 0.75rem;">
                        "{original}"
                    </div>
                    
                    <div style="display: flex; flex-wrap: wrap; gap: 0.5rem; margin-bottom: 0.75rem;">
                        <span style="background: #e0e7ff; color: #3730a3; padding: 2px 8px; border-radius: 4px; font-size: 0.8rem;">
                            <strong>S:</strong> {situation or 'Context established'}
                        </span>
                        <span style="background: #fef3c7; color: #92400e; padding: 2px 8px; border-radius: 4px; font-size: 0.8rem;">
                            <strong>T:</strong> {task or 'Objective defined'}
                        </span>
                        <span style="background: #dbeafe; color: #1e40af; padding: 2px 8px; border-radius: 4px; font-size: 0.8rem;">
                            <strong>A:</strong> {action or 'Technical action applied'}
                        </span>
                        <span style="background: #dcfce7; color: #166534; padding: 2px 8px; border-radius: 4px; font-size: 0.8rem;">
                            <strong>R:</strong> {result or 'Quantified impact'}
                        </span>
                    </div>

                    <div style="font-size: 0.8rem; font-weight: 700; color: #16a34a; 
                                text-transform: uppercase; letter-spacing: 0.05em; margin-bottom: 0.25rem;">
                        ✅ High-Impact STAR Revision
                    </div>
                    <div style="background-color: #ffffff; border: 1px solid #cbd5e1; border-radius: 6px; 
                                padding: 0.75rem 1rem; color: #0f172a; font-weight: 600; margin-bottom: 0.5rem;">
                        {improved}
                    </div>
                    
                    <div style="font-size: 0.85rem; color: #64748b;">
                        <strong>💡 Recruiter & ATS Impact:</strong> {explanation}
                    </div>
                </div>
                """,
                unsafe_allow_html=True,
            )
